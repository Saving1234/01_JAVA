package lecture.section01.literal;

public class Apllicationn1 {

    public static void main(String[] args) {

        System.out.println(123); //정수형
        System.out.println(1.23); //실수형
        System.out.println("1.23"); //문자형

        //문자형태의 값
        //비어있으면 안된다.

        System.out.println('c');
        System.out.println('z');

        //문자열
        //비어있어도 상관없다

        System.out.println(" ");
        System.out.println("사이다");
        System.out.println("먹고싶다");
        System.out.println("한모금만");
        System.out.println("1234");
        System.out.println(1234);

        //논리형태의 값
        System.out.println(true);
        System.out.println(false);



    }
}
